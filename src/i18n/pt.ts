/** Mesmo formato do português, com qualquer texto no lugar de cada texto. */
type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => infer R
    ? (...args: A) => R
    : { [K in keyof T]: Widen<T[K]> };

export type Dict = Widen<typeof pt>;
